// Bundle individually authored community patches into one browser module.
//
// Git distributes the files; this script only turns their source into importable data.
// It deliberately does not execute student code.

import { mkdir, readFile, readdir, writeFile } from 'node:fs/promises';
import { basename, dirname, extname, join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = fileURLToPath(new URL('..', import.meta.url));
const SOURCE_DIR = fileURLToPath(new URL('../community-patches/', import.meta.url));
const OUTPUT = fileURLToPath(
  new URL('../src/generated/communityPatches.js', import.meta.url),
);

const metadata = (source, field) =>
  new RegExp(`^//\\s*@${field}\\s+(.+)$`, 'm').exec(source)?.[1].trim() ?? null;

const CATEGORIES = new Set(['visual', 'utility', 'shader', 'user']);

const files = (await readdir(SOURCE_DIR))
  .filter((file) => extname(file) === '.js')
  .sort((a, b) => a.localeCompare(b));

const entries = [];
const names = new Set();

for (const file of files) {
  const source = await readFile(join(SOURCE_DIR, file), 'utf8');
  const marker = /^\/\/\s*%%\s*patch\s+([A-Za-z_$][\w$]*)\s*$/m.exec(source);
  if (!marker) throw new Error(`${file} needs a "// %% patch bindingName" marker`);

  const name = marker[1];
  if (names.has(name)) throw new Error(`More than one community patch declares "${name}"`);
  names.add(name);

  const title = metadata(source, 'title');
  const author = metadata(source, 'author');
  const blurb = metadata(source, 'description');
  const category = metadata(source, 'category');
  if (!title || !author || !blurb || !category) {
    throw new Error(`${file} needs @title, @author, @description, and @category comments`);
  }
  if (!CATEGORIES.has(category)) {
    throw new Error(
      `${file} has unknown @category "${category}"; use visual, utility, shader, or user`,
    );
  }

  entries.push({
    name,
    title,
    author,
    blurb,
    category,
    source: source.trimEnd(),
    origin: 'student',
    file: basename(file),
  });
}

await mkdir(dirname(OUTPUT), { recursive: true });
await writeFile(
  OUTPUT,
  `// Generated by scripts/build-patch-library.mjs — do not edit.\n` +
    `export const COMMUNITY_PATCHES = Object.freeze(${JSON.stringify(entries, null, 2)});\n`,
);

console.log(`Bundled ${entries.length} community patches from ${relative(ROOT, SOURCE_DIR)}`);
